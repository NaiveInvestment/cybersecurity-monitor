import {readFileSync,writeFileSync,mkdirSync} from "node:fs";
import {join} from "node:path";
import {ROOT,loadUniverse} from "../src/universe.mjs";
import {fetchDaily,fetchRealtime,mapLimit} from "../src/naver.mjs";
const args=process.argv.slice(2), out=args.includes("--out")?args[args.indexOf("--out")+1]:join(ROOT,"_site","data");
const membership=JSON.parse(readFileSync(join(ROOT,"data","sector-membership.json"),"utf8"));
membership.groups.push(...JSON.parse(readFileSync(join(ROOT,"data","sector-extra.json"),"utf8")).groups);
const domestic=loadUniverse().stocks.filter(s=>s.kind==="KR");
const groups=[{id:"security",name:"보안",reference:"사이버보안 모니터",asOf:loadUniverse().asOf,stocks:domestic.map(s=>({code:s.code,name:s.name}))},...membership.groups];
const unique=[...new Set(groups.flatMap(g=>g.stocks.map(s=>s.code)))];
const compact=d=>d.toISOString().slice(0,10).replaceAll("-","");
const now=new Date(), start=new Date(now.getTime()-410*86400000), range={start:compact(start),end:compact(new Date(now.getTime()+86400000))};
const quotes=await fetchRealtime("KR",unique);
const results=await mapLimit(unique,5,async code=>[code,await fetchDaily("KR",code,range)]);
if(results.some(r=>r.error)) throw new Error(results.filter(r=>r.error).map(r=>r.error).join('; '));
const histories=results.map(r=>r.value);
const stocks=Object.fromEntries(histories.map(([code,history])=>[code,{history,cap:quotes[code]?.cap,p:quotes[code]?.p}]));
const benchmarks=await Promise.all([['KOSPI','코스피'],['KOSDAQ','코스닥']].map(async([id,name])=>({id,name,history:await fetchDaily("KR",id,{...range,type:"index"})})));
if(histories.some(([,h])=>!h.length)) throw new Error("섹터 구성종목 일봉 누락");
mkdirSync(out,{recursive:true});
writeFileSync(join(out,"sectors.json"),JSON.stringify({generatedAt:now.toISOString(),membershipAsOf:membership.asOf,groups,stocks,benchmarks}));
console.log('섹터 구성',groups.map(g=>`${g.name} ${g.stocks.length}`).join(', '));
